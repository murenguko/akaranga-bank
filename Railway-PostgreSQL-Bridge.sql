              'Operations', 'VirementsInterAgences', 'DocumentAcces', 'AlertesAML',
              'Ecritures', 'TransactionsCarte', 'DeclarationsSoupcon'
          )
    LOOP
        EXECUTE format('SELECT max("Id") FROM public.%I', target_table) INTO max_id;
        PERFORM setval(
            pg_get_serial_sequence(format('public.%I', target_table), 'Id'),
            COALESCE(max_id, 1),
            max_id IS NOT NULL
        );
    END LOOP;
END
