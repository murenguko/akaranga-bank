-- One-time bridge from AkarangaBank-Script-DB-PostgreSQL.sql to the EF/Npgsql model.
-- Run against the SAME Railway database as the application, after taking a backup.
-- The original lowercase tables and their rows are left untouched.
-- All changes are transactional; a failed statement rolls the bridge back.
BEGIN;
SET LOCAL search_path TO public;
SET LOCAL TIME ZONE 'UTC';

DO $preflight$
DECLARE
    source_table text;
BEGIN
    FOREACH source_table IN ARRAY ARRAY[
        'agences', 'utilisateurs', 'parametres', 'clients', 'verificationskyc',
        'typescompte', 'comptes', 'cartes', 'prets', 'echeancespret', 'virements',
        'operations', 'ecritures', 'auditlog', 'alertesaml', 'sessionsutilisateur'
    ] LOOP
        IF to_regclass('public.' || source_table) IS NULL THEN
            RAISE EXCEPTION 'Missing legacy table public.%', source_table;
        END IF;
    END LOOP;

    IF to_regclass('public."Agences"') IS NOT NULL THEN
        RAISE EXCEPTION 'The app schema already exists; stop and inspect it before rerunning this bridge';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM utilisateurs u
        LEFT JOIN agences a ON a.code = u.agence_code
        WHERE a.id IS NULL OR (u.agenceid IS NOT NULL AND u.agenceid <> a.id)
    ) THEN
        RAISE EXCEPTION 'A legacy user has an invalid or conflicting agency';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM utilisateurs
        GROUP BY upper(CASE WHEN username LIKE '%@%' THEN username ELSE username || '@akaranga.bi' END)
        HAVING count(*) > 1
    ) THEN
        RAISE EXCEPTION 'Legacy usernames would produce duplicate Identity emails';
    END IF;
END
$preflight$;

