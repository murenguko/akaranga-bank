    max_id bigint;
BEGIN
    FOR target_table IN
        SELECT table_name
        FROM information_schema.columns
        WHERE table_schema = 'public' AND column_name = 'Id' AND is_identity = 'YES'
          AND table_name IN (
              'Agences', 'NotificationTemplates', 'Roles', 'SeuilsAML', 'TypesCompte',
              'Clients', 'Parametres', 'Utilisateur', 'RolesClaims', 'Comptes',
              'Utilisateurs', 'Cartes', 'CompensationsAgences', 'AuditLog',
